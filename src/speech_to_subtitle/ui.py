from __future__ import annotations

import tkinter as tk
from tkinter import ttk

BG, PANEL, FIELD, LINE = "#0b0d12", "#141720", "#1b1f2b", "#292e3d"
TEXT, MUTED, ACCENT, GREEN = "#eff1f8", "#929bb1", "#9f91ff", "#78d7af"


def build_ui(app):
    app.configure(bg=BG)
    style = ttk.Style(app)
    style.theme_use("clam")
    style.configure(".", background=BG, foreground=TEXT, bordercolor=LINE, lightcolor=LINE, darkcolor=LINE, font=("Microsoft YaHei UI", 10))
    style.configure("TFrame", background=BG)
    style.configure("Card.TFrame", background=PANEL)
    style.configure("TLabel", background=BG, foreground=TEXT)
    style.configure("Muted.TLabel", foreground=MUTED)
    style.configure("Card.TLabel", background=PANEL)
    style.configure("Title.TLabel", font=("Microsoft YaHei UI", 25, "bold"))
    style.configure("Section.TLabel", font=("Microsoft YaHei UI", 12, "bold"))
    style.configure("TButton", padding=(15, 9), background=FIELD, borderwidth=0)
    style.map("TButton", background=[("active", "#30354a"), ("disabled", "#171a22")], foreground=[("disabled", "#626979")])
    style.configure("Primary.TButton", background=ACCENT, foreground="#151020", font=("Microsoft YaHei UI", 10, "bold"))
    style.map("Primary.TButton", background=[("active", "#b5abff"), ("disabled", "#393347")])
    style.configure("TEntry", fieldbackground=FIELD, foreground=TEXT, insertcolor=TEXT, padding=9)
    style.configure("TCombobox", fieldbackground=FIELD, foreground=TEXT, arrowcolor=MUTED, padding=7)
    style.map("TCombobox", fieldbackground=[("readonly", FIELD)], foreground=[("readonly", TEXT)])
    style.configure("TCheckbutton", background=BG, indicatorbackground=FIELD, indicatorforeground=ACCENT, padding=(0, 5))
    style.map("TCheckbutton", background=[("active", BG)])
    style.configure("Horizontal.TProgressbar", background=ACCENT, troughcolor=LINE, borderwidth=0, thickness=5)
    style.configure("Treeview", background=PANEL, fieldbackground=PANEL, foreground=TEXT, rowheight=36, borderwidth=0)
    style.configure("Treeview.Heading", background=FIELD, foreground=MUTED, padding=(10, 9), relief="flat")
    style.map("Treeview", background=[("selected", "#393451")])

    shell = ttk.Frame(app, padding=24)
    shell.pack(fill="both", expand=True)
    sidebar = ttk.Frame(shell, width=225)
    sidebar.pack(side="left", fill="y", padx=(0, 28))
    sidebar.pack_propagate(False)
    ttk.Label(sidebar, text="◉  LISTEN / 本地", foreground=ACCENT, font=("Segoe UI", 12, "bold")).pack(anchor="w", pady=(5, 4))
    ttk.Label(sidebar, text="听见字幕", style="Muted.TLabel").pack(anchor="w", pady=(0, 31))
    ttk.Label(sidebar, text="识别模型", style="Section.TLabel").pack(anchor="w", pady=(0, 8))
    ttk.Combobox(sidebar, textvariable=app.model_var, values=tuple(app_model_labels()), state="readonly", width=22).pack(fill="x", pady=(0, 8))
    ttk.Label(sidebar, text="Small 适合首次使用；Turbo 和 Large 首次需下载较大模型。", style="Muted.TLabel", wraplength=215, justify="left").pack(anchor="w", pady=(0, 22))
    ttk.Label(sidebar, text="识别语言", style="Section.TLabel").pack(anchor="w", pady=(0, 8))
    ttk.Combobox(sidebar, textvariable=app.language_var, values=("自动识别", "中文", "英语", "日语", "韩语", "法语", "德语", "西班牙语"), state="readonly", width=22).pack(fill="x", pady=(0, 18))
    ttk.Label(sidebar, text="运行设备", style="Section.TLabel").pack(anchor="w", pady=(0, 8))
    ttk.Combobox(sidebar, textvariable=app.device_var, values=("自动 · GPU 优先", "NVIDIA GPU", "CPU"), state="readonly", width=22).pack(fill="x")
    ttk.Label(sidebar, text="自动模式在 GPU 库不可用时会切换 CPU。", style="Muted.TLabel", wraplength=215, justify="left").pack(anchor="w", pady=(8, 18))
    ttk.Label(sidebar, text="识别设置", style="Section.TLabel").pack(anchor="w", pady=(0, 6))
    ttk.Combobox(sidebar, textvariable=app.script_var, values=("简体中文", "繁体中文", "保持原样"), state="readonly", width=22).pack(fill="x", pady=(0, 4))
    ttk.Label(sidebar, text="中文输出 · 下次识别生效", style="Muted.TLabel").pack(anchor="w", pady=(0, 4))
    ttk.Checkbutton(sidebar, text="过滤静音", variable=app.vad_var).pack(anchor="w")
    ttk.Checkbutton(sidebar, text="词级时间戳", variable=app.words_var).pack(anchor="w")
    ttk.Label(sidebar, text="输出格式", style="Section.TLabel").pack(anchor="w", pady=(20, 6))
    formats = ttk.Frame(sidebar)
    formats.pack(fill="x")
    ttk.Checkbutton(formats, text="SRT", variable=app.srt_var).grid(row=0, column=0, sticky="w")
    ttk.Checkbutton(formats, text="VTT", variable=app.vtt_var).grid(row=0, column=1, sticky="w", padx=(16, 0))
    ttk.Checkbutton(formats, text="TXT", variable=app.txt_var).grid(row=1, column=0, sticky="w")
    ttk.Checkbutton(formats, text="JSON", variable=app.json_var).grid(row=1, column=1, sticky="w", padx=(16, 0))
    ttk.Label(sidebar, text="v0.1.1  ·  faster-whisper\n模型与文件仅保存在本机", style="Muted.TLabel", justify="left").pack(side="bottom", anchor="w")

    main = ttk.Frame(shell)
    main.pack(side="left", fill="both", expand=True)
    main.columnconfigure(0, weight=1)
    main.rowconfigure(4, weight=1)
    ttk.Label(main, text="让声音，变成可以编辑的字幕。", style="Title.TLabel").grid(row=0, column=0, sticky="w")
    ttk.Label(main, text="视频和音频都在本机识别，输出通用字幕与纯文字稿。", style="Muted.TLabel").grid(row=1, column=0, sticky="w", pady=(6, 20))
    card = ttk.Frame(main, style="Card.TFrame", padding=17)
    card.grid(row=2, column=0, sticky="ew")
    card.columnconfigure(1, weight=1)
    ttk.Label(card, text="01", style="Card.TLabel", foreground=ACCENT, font=("Segoe UI", 11, "bold")).grid(row=0, column=0, sticky="w", padx=(0, 12))
    ttk.Label(card, text="选择媒体", style="Card.TLabel", font=("Microsoft YaHei UI", 11, "bold")).grid(row=0, column=1, sticky="w")
    ttk.Entry(card, textvariable=app.source_var, font=("Segoe UI", 10)).grid(row=1, column=0, columnspan=2, sticky="ew", pady=(12, 0))
    app.source_button = ttk.Button(card, text="选择文件", command=app.choose_source)
    app.source_button.grid(row=1, column=2, padx=(8, 0), pady=(12, 0))
    ttk.Label(card, text="输出到", style="Card.TLabel").grid(row=2, column=0, sticky="w", pady=(12, 0))
    ttk.Entry(card, textvariable=app.output_var).grid(row=2, column=1, sticky="ew", pady=(12, 0))
    ttk.Button(card, text="选择目录", command=app.choose_output).grid(row=2, column=2, padx=(8, 0), pady=(12, 0))
    ttk.Label(card, text="词汇提示", style="Card.TLabel").grid(row=3, column=0, sticky="w", pady=(12, 0))
    ttk.Entry(card, textvariable=app.prompt_var).grid(row=3, column=1, columnspan=2, sticky="ew", pady=(12, 0))
    actions = ttk.Frame(main)
    actions.grid(row=3, column=0, sticky="ew", pady=(14, 17))
    app.start_button = ttk.Button(actions, text="▶  开始识别", style="Primary.TButton", command=app.start)
    app.start_button.pack(side="left")
    app.stop_button = ttk.Button(actions, text="停止", command=app.stop, state="disabled")
    app.stop_button.pack(side="left", padx=8)
    ttk.Button(actions, text="打开输出目录 ↗", command=app.open_output).pack(side="right")
    result = ttk.Frame(main)
    result.grid(row=4, column=0, sticky="nsew")
    result.columnconfigure(0, weight=1)
    result.rowconfigure(1, weight=1)
    ttk.Label(result, text="02   字幕预览", style="Section.TLabel").grid(row=0, column=0, sticky="w", pady=(0, 9))
    ttk.Label(result, textvariable=app.summary_var, style="Muted.TLabel").grid(row=0, column=1, sticky="e", pady=(0, 9))
    table_wrap = ttk.Frame(result, style="Card.TFrame")
    table_wrap.grid(row=1, column=0, columnspan=2, sticky="nsew")
    table_wrap.rowconfigure(0, weight=1)
    table_wrap.columnconfigure(0, weight=1)
    app.table = ttk.Treeview(table_wrap, columns=("index", "start", "end", "text"), show="headings", selectmode="browse")
    for name, title, width in (("index", "序号", 55), ("start", "开始", 75), ("end", "结束", 75), ("text", "字幕文字", 580)):
        app.table.heading(name, text=title, anchor="w")
        app.table.column(name, width=width, stretch=name == "text")
    app.table.grid(row=0, column=0, sticky="nsew")
    app.table.bind("<<TreeviewSelect>>", app.on_select)
    scroll = ttk.Scrollbar(table_wrap, orient="vertical", command=app.table.yview)
    scroll.grid(row=0, column=1, sticky="ns")
    app.table.configure(yscrollcommand=scroll.set)
    edit = ttk.Frame(result)
    edit.grid(row=2, column=0, columnspan=2, sticky="ew", pady=(9, 0))
    edit.columnconfigure(0, weight=1)
    app.preview = tk.Text(edit, height=3, bg=FIELD, fg=TEXT, insertbackground=TEXT, relief="flat", padx=11, pady=8, wrap="word", font=("Microsoft YaHei UI", 10))
    app.preview.grid(row=0, column=0, sticky="ew")
    ttk.Button(edit, text="应用本条", command=app.apply_edit).grid(row=0, column=1, padx=(8, 0))
    app.save_button = ttk.Button(edit, text="保存修改", command=app.save_edits, state="disabled")
    app.save_button.grid(row=0, column=2, padx=(8, 0))
    status = ttk.Frame(main)
    status.grid(row=5, column=0, sticky="ew", pady=(14, 0))
    ttk.Label(status, textvariable=app.status_var, style="Muted.TLabel").pack(side="left")
    ttk.Label(status, textvariable=app.progress_text_var, foreground=ACCENT).pack(side="right")
    app.progress = ttk.Progressbar(main, variable=app.progress_var, maximum=100)
    app.progress.grid(row=6, column=0, sticky="ew", pady=(8, 0))


def app_model_labels():
    return ("Tiny · 测试", "Base · 很快", "Small · 推荐", "Medium · 更准确", "Turbo · GPU 推荐", "Large v3 · 最高精度")
